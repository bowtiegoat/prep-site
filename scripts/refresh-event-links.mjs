// Rebuilds docs/js/event-links.js: each event's guidelines PDF (scraped from
// its deca.org page) and its DECA+ page. DECA posts new guideline PDFs each
// school year, so run this when they do:  node scripts/refresh-event-links.mjs

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// Same list as docs/js/events.js, in the CommonJS copy Node can load directly.
const EVENTS = createRequire(import.meta.url)('../functions/events.js');

async function guidelinesFor(url) {
  const html = await (await fetch(url)).text();
  const pdfs = [...new Set(html.match(/https:\/\/cdn[^"\s]*?\.pdf/g) || [])];
  return pdfs.find((p) => /guideline/i.test(p)) || '';
}

async function decaPlusFor(url) {
  const page = `https://www.decaplus.org/competitive-events/${url.replace(/\/$/, '').split('/').pop()}`;
  const res = await fetch(page, { method: 'HEAD' });
  return res.ok ? page : '';
}

const links = {};
for (const e of EVENTS) {
  const [guidelines, decaPlus] = await Promise.all([guidelinesFor(e.url), decaPlusFor(e.url)]);
  links[e.code] = { guidelines, decaPlus };
  console.log(e.code.padEnd(6), guidelines ? 'guidelines ✓' : 'guidelines ✗', decaPlus ? 'DECA+ ✓' : 'DECA+ ✗');
}

const today = new Date().toLocaleDateString('en-CA');
writeFileSync(new URL('../docs/js/event-links.js', import.meta.url), `// Per-event resource links. Generated by scripts/refresh-event-links.mjs on ${today}.
// The DECA event page itself is each event's url in events.js.
export const EVENT_LINKS = ${JSON.stringify(links, null, 2)};
`);
